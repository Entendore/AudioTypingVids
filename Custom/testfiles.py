"""
SuperCollider Arpeggio Generator (Pure NRT OSC Bundles)
--------------------------------------------------------
Generates .scd files containing musical arpeggios.
Correctly utilizes __DURATION__ to define the exact length of the NRT render.
Designed to work seamlessly with the SuperCollider NRT Visualizer's 
"Audio Matches Typing (SC Renders to Match)" behavior.
"""

import os
import random

OUTPUT_FOLDER = "sc_input"
NUMBER_OF_FILES = 100

os.makedirs(OUTPUT_FOLDER, exist_ok=True)

NOTE_NAMES = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"]
SCALES = {
    "Major": [0,2,4,5,7,9,11], "NaturalMinor": [0,2,3,5,7,8,10],
    "Dorian": [0,2,3,5,7,9,10], "Phrygian": [0,1,3,5,7,8,10],
    "Lydian": [0,2,4,6,7,9,11], "Mixolydian": [0,2,4,5,7,9,10],
    "Locrian": [0,1,3,5,6,8,10], "Pentatonic": [0,2,4,7,9],
    "Blues": [0,3,5,6,7,10], "HarmonicMinor": [0,2,3,5,7,8,11]
}
CHORDS = {
    "Major":[0,4,7], "Minor":[0,3,7], "Dim":[0,3,6], "Aug":[0,4,8],
    "Sus2":[0,2,7], "Sus4":[0,5,7], "Maj7":[0,4,7,11], "Min7":[0,3,7,10], "Dom7":[0,4,7,10]
}

PATTERNS = ["up", "down", "updown", "random"]

SYNTHS = [
    {
        "name": "synth_saw",
        "code": """synth = SynthDef(\\synth_saw, { arg out=0, freq=440, amp=0.5;
    var sig, env;
    env = EnvGen.ar(Env.perc(0.01, 0.4), doneAction: 2);
    sig = Saw.ar(freq) * 0.5 + Pulse.ar(freq, width: 0.3) * 0.5;
    Out.ar(out, sig * env * amp ! 2);
});"""
    },
    {
        "name": "synth_bell",
        "code": """synth = SynthDef(\\synth_bell, { arg out=0, freq=440, amp=0.5;
    var sig, env, mod;
    env = EnvGen.ar(Env.perc(0.001, 1.5), doneAction: 2);
    mod = SinOsc.ar(freq * 3.01) * freq * 2;
    sig = SinOsc.ar(freq + mod);
    Out.ar(out, sig * env * amp ! 2);
});"""
    },
    {
        "name": "synth_pluck",
        "code": """synth = SynthDef(\\synth_pluck, { arg out=0, freq=440, amp=0.5;
    var sig, env;
    env = EnvGen.ar(Env.linen(0.001, 0.2, 0.8), doneAction: 2);
    sig = Pluck.ar(WhiteNoise.ar(0.5), Impulse.kr(0), freq.reciprocal, freq.reciprocal, 10, coef:0.4);
    Out.ar(out, sig * env * amp ! 2);
});"""
    },
    {
        "name": "synth_bass",
        "code": """synth = SynthDef(\\synth_bass, { arg out=0, freq=440, amp=0.5;
    var sig, env;
    env = EnvGen.ar(Env.perc(0.01, 0.6), doneAction: 2);
    sig = Saw.ar(freq * 0.5) + SinOsc.ar(freq * 0.5);
    Out.ar(out, sig * env * amp ! 2);
});"""
    },
    {
        "name": "synth_pad",
        "code": """synth = SynthDef(\\synth_pad, { arg out=0, freq=440, amp=0.5;
    var sig, env;
    env = EnvGen.ar(Env.perc(0.5, 2.5), doneAction: 2);
    sig = SinOsc.ar(freq) + SinOsc.ar(freq * 1.005) + Saw.ar(freq * 0.5, mul: 0.2);
    Out.ar(out, sig * env * amp * 0.5 ! 2);
});"""
    }
]

def build_chord(root_note, chord_intervals): return [root_note + i for i in chord_intervals]

def make_pattern(notes, pattern):
    if pattern == "up": return notes
    elif pattern == "down": return notes[::-1]
    elif pattern == "updown": return notes + notes[-2:0:-1]
    elif pattern == "random":
        n = notes.copy(); random.shuffle(n); return n
    return notes

def repeat_pattern(notes, repeats=4):
    output = []
    for _ in range(repeats): output.extend(notes)
    return output

# Notice: ALL 'var' declarations are at the very top. 
# 'duration' is now used to calculate note_dur so the arpeggio fits perfectly.
SCD_TEMPLATE = """// ======================================================
// Generated by Python (Pure NRT OSC Bundles)
// Designed for the SC NRT Visualizer
// ======================================================

(
var def, synth, bundles, melody, amp, synth_name, t, total_dur, 
    duration, note_count, note_dur;

// Information
"Root: __ROOT__".postln;
"Scale: __SCALE__".postln;
"Chord: __CHORD__".postln;
"Pattern: __PATTERN__".postln;
"Instrument: __SYNTH_NAME__".postln;

// 1. Assign variables
// The NRT Visualizer will automatically replace the __DURATION__ placeholder
// with the exact length of the typing animation when "SC Renders to Match" is used.
duration = __DURATION__;

// Define the selected synthesizer
__SYNTH_CODE__
def = synth.asBytes;

melody     = [__MELODY__];
amp        = __AMP__;
synth_name = \\__SYNTH_NAME__;
note_count = melody.size;

// 2. Calculate note duration to fit exactly into the requested duration
// Leave 0.5s lead-in for synth def to load, and 1.0s tail for final release
note_dur = max((duration - 0.5 - 1.0) / note_count, 0.05);

// 3. Initialize empty bundles array
bundles = [];

// 4. Add SynthDef at time 0.0
bundles = bundles.add([0.0, [\\d_recv, def]]);

// 5. Manually schedule notes
t = 0.5; // Start time offset to ensure def is loaded
melody.do({ arg midi_note, i;
    var freq = midi_note.midicps;
    var node_id = 1000 + i; // Unique node ID per note
    bundles = bundles.add([t, [\\s_new, synth_name, node_id, 0, 0, \\freq, freq, \\amp, amp]]);
    t = t + note_dur;
});

// 6. Add cleanup commands at the exact requested duration
total_dur = duration;
bundles = bundles.add([total_dur, [\\g_freeAll, 0]]);
bundles = bundles.add([total_dur + 0.01, [\\c_set, 0, 0]]); // NRT quit flag

// 7. Write raw OSC to file using built-in Score class
// The NRT Visualizer automatically replaces __SCORE_PATH__ with the temp file path.
Score.write(bundles, "__SCORE_PATH__");

// 8. Signal Python that the file is ready
"SCORE_WRITTEN".postln;
)
"""

for index in range(NUMBER_OF_FILES):
    root_name = random.choice(NOTE_NAMES)
    octave = random.randint(3,5)
    root_index = NOTE_NAMES.index(root_name)
    midi_root = root_index + (octave + 1) * 12
    
    chord_name = random.choice(list(CHORDS.keys()))
    scale_name = random.choice(list(SCALES.keys()))
    pattern_name = random.choice(PATTERNS)
    amp = round(random.uniform(0.3, 0.6), 2)

    synth_choice = random.choice(SYNTHS)
    synth_name = synth_choice["name"]
    synth_code = synth_choice["code"]

    chord = build_chord(midi_root, CHORDS[chord_name])
    melody = make_pattern(chord, pattern_name)
    melody = repeat_pattern(melody, random.randint(4,12))
    
    melody_string = ", ".join(str(n) for n in melody)

    scd = SCD_TEMPLATE.replace("__ROOT__", f"{root_name}{octave}")
    scd = scd.replace("__SCALE__", scale_name)
    scd = scd.replace("__CHORD__", chord_name)
    scd = scd.replace("__PATTERN__", pattern_name)
    scd = scd.replace("__SYNTH_NAME__", synth_name)
    scd = scd.replace("__SYNTH_CODE__", synth_code)
    scd = scd.replace("__MELODY__", melody_string)
    # __DURATION__ is intentionally left as a string placeholder so the visualizer 
    # can inject the exact typing time for "SC Renders to Match".
    scd = scd.replace("__AMP__", str(amp))

    filename = os.path.join(OUTPUT_FOLDER, f"arpeggio_{index+1:04}.scd")
    with open(filename, "w", encoding="utf-8") as f:
        f.write(scd)

print(f"Generated {NUMBER_OF_FILES} Pure NRT OSC Bundle files in '{OUTPUT_FOLDER}/'.")