def build_chord(root_note, chord_intervals): return [root_note + i for i in chord_intervals]
def make_pattern(notes, pattern):
    if pattern == "up": return notes
    elif pattern == "down": return notes[::-1]
    elif pattern == "updown": return notes + notes[-2:0:-1]
    elif pattern == "random":
        n = notes.copy(); random.shuffle(n); return n
    return notes
def repeat_pattern(notes, repeats=4):
    output = []
    for _ in range(repeats): output.extend(notes)
    return output

SCD_TEMPLATE = """// ======================================================
// Generated by Python (NRT Audio Final Fix)
// ======================================================

(
var pbind, score, dur_total, synth;

// CRITICAL: Trick SC into thinking the server is booted.
Server.default = Server.local;
Server.default.isRunning = true;

// CRITICAL: Assign a basic default group so Pbind knows where to send notes!
Server.default.defaultGroup = Group.basicNew(Server.default, 1);

// Information
"Root: __ROOT__".postln;
"Scale: __SCALE__".postln;
"Chord: __CHORD__".postln;
"Pattern: __PATTERN__".postln;
"Instrument: __SYNTH_NAME__".postln;
"BPM: __BPM__".postln;

TempoClock.default.tempo = __BPM__/60;

// 1. Define the selected synthesizer
__SYNTH_CODE__

// 2. Create the musical pattern
pbind = Pbind(
    \\instrument, \\__SYNTH_NAME__,
    \\midinote, Pseq([__MELODY__], 1),
    \\dur, __DUR__,
    \\amp, __AMP__
);

dur_total = __TOTAL_DUR__;

// 3. Convert pattern to an NRT score
score = pbind.asScore(dur_total, 0.1);

// 4. Create the default group at time 0.0
score.add([0.0, [\\g_new, 1, 0, 0]]);

// 5. Add the SynthDef binary to the score at time 0.0
score.add([0.0, [\\d_recv, synth.asBytes]]);

// 6. Write the score
score.write("__SCORE_PATH__");

// 7. Exit sclang
0.exit;
)
"""

for index in range(NUMBER_OF_FILES):
    root_name = random.choice(NOTE_NAMES)
    octave = random.randint(3,5)
    root_index = NOTE_NAMES.index(root_name)
    midi_root = root_index + (octave + 1) * 12
    
    chord_name = random.choice(list(CHORDS.keys()))
    scale_name = random.choice(list(SCALES.keys()))
    pattern_name = random.choice(PATTERNS)
    bpm = random.randint(70,160)
    duration = random.choice(RHYTHMS)
    # Bumped amp slightly to ensure it's loud and clear
    amp = round(random.uniform(0.3, 0.6), 2)

    synth_choice = random.choice(SYNTHS)
    synth_name = synth_choice["name"]
    synth_code = synth_choice["code"]

    chord = build_chord(midi_root, CHORDS[chord_name])
    melody = make_pattern(chord, pattern_name)
    melody = repeat_pattern(melody, random.randint(4,12))
    
    melody_string = ", ".join(str(n) for n in melody)
    total_duration = len(melody) * duration + 2.0

    scd = SCD_TEMPLATE.replace("__ROOT__", f"{root_name}{octave}")
    scd = scd.replace("__SCALE__", scale_name)
    scd = scd.replace("__CHORD__", chord_name)
    scd = scd.replace("__PATTERN__", pattern_name)
    scd = scd.replace("__SYNTH_NAME__", synth_name)
    scd = scd.replace("__SYNTH_CODE__", synth_code)
    scd = scd.replace("__BPM__", str(bpm))
    scd = scd.replace("__MELODY__", melody_string)
    scd = scd.replace("__DUR__", str(duration))
    scd = scd.replace("__AMP__", str(amp))
    scd = scd.replace("__TOTAL_DUR__", str(total_duration))

    filename = os.path.join(OUTPUT_FOLDER, f"arpeggio_{index+1:04}.scd")
    with open(filename, "w", encoding="utf-8") as f:
        f.write(scd)

print(f"Generated {NUMBER_OF_FILES} NRT-compatible files.")